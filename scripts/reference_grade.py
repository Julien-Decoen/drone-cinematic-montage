#!/usr/bin/env python3
"""reference_grade.py — Extract palette from a reference image, generate matching LUT.

Pick a still you love (a frame from Wes Anderson, an Apple ad, a Sam Kolder
edit) and this script:
  1. Extracts the dominant N colors via k-means (sklearn)
  2. Generates a CUBE LUT (33×33×33) that pushes source midtones toward
     that palette while preserving extremes
  3. Optionally previews the LUT applied on your master

You can then plug that LUT into your render template via LUT_SRC.

Usage:
    python3 reference_grade.py reference.jpg                        # → reference_grade.cube
    python3 reference_grade.py ref.jpg --palette 5 --strength 0.6   # 5 colors, gentler push
    python3 reference_grade.py ref.jpg --preview master.mp4         # also export preview_graded.mp4

Requires:  pip install scikit-learn pillow numpy
"""
import argparse
import shutil
import subprocess
import sys
from pathlib import Path

try:
    import numpy as np
    from PIL import Image
    from sklearn.cluster import KMeans
except ImportError:
    sys.exit("❌ Install: pip install scikit-learn pillow 'numpy<2'")

FFMPEG = shutil.which("ffmpeg") or "/opt/homebrew/bin/ffmpeg"
LUT_SIZE = 33  # standard cube size


def extract_palette(image_path: Path, n_colors: int) -> np.ndarray:
    img = Image.open(image_path).convert("RGB")
    img.thumbnail((400, 400))
    arr = np.asarray(img).reshape(-1, 3) / 255.0
    km = KMeans(n_clusters=n_colors, n_init=4, random_state=42)
    km.fit(arr)
    centers = km.cluster_centers_
    counts = np.bincount(km.labels_)
    # Sort by frequency desc
    order = np.argsort(-counts)
    return centers[order], counts[order] / counts.sum()


def generate_cube_lut(palette: np.ndarray, weights: np.ndarray, strength: float, out_path: Path):
    """Generate a 33×33×33 CUBE LUT that pulls midtones toward the palette centroid."""
    # Target = weighted mean of the palette (the overall "feel" color)
    target = (palette * weights[:, None]).sum(axis=0)

    # For each lattice point, lerp toward target proportional to mid-tone-ness
    # (extremes stay, midtones shift). Use a bell curve on luminance.
    with open(out_path, "w") as f:
        f.write(f"# Generated by reference_grade.py\n")
        f.write(f"# Palette ({len(palette)} colors):\n")
        for c, w in zip(palette, weights):
            f.write(f"#   RGB({c[0]*255:.0f},{c[1]*255:.0f},{c[2]*255:.0f})  w={w:.2f}\n")
        f.write(f"# Strength: {strength}\n")
        f.write(f"LUT_3D_SIZE {LUT_SIZE}\n")
        for b in range(LUT_SIZE):
            for g in range(LUT_SIZE):
                for r in range(LUT_SIZE):
                    rgb = np.array([r, g, b]) / (LUT_SIZE - 1)
                    lum = 0.2126 * rgb[0] + 0.7152 * rgb[1] + 0.0722 * rgb[2]
                    # Bell weight: 1 at lum=0.5, 0 at 0/1
                    w = 4 * lum * (1 - lum)
                    shift = strength * w
                    out = rgb * (1 - shift) + target * shift
                    out = np.clip(out, 0, 1)
                    f.write(f"{out[0]:.6f} {out[1]:.6f} {out[2]:.6f}\n")


def apply_lut_preview(input_video: Path, lut_path: Path, output_video: Path,
                      duration: float = 10.0):
    cmd = [FFMPEG, "-y", "-loglevel", "error",
           "-i", str(input_video), "-t", f"{duration:.1f}",
           "-vf", f"lut3d={lut_path}",
           "-c:v", "libx264", "-preset", "veryfast", "-crf", "22",
           "-c:a", "copy",
           str(output_video)]
    subprocess.run(cmd, capture_output=True)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("reference", help="Reference image (jpg/png)")
    p.add_argument("--palette", type=int, default=5, help="Number of palette colors (3-8, default 5)")
    p.add_argument("--strength", type=float, default=0.4, help="LUT push strength 0-1 (default 0.4)")
    p.add_argument("--out", help="Output LUT path (default: <ref>_grade.cube)")
    p.add_argument("--preview", help="Apply LUT to this video and save preview_graded.mp4")
    args = p.parse_args()

    ref = Path(args.reference).expanduser().resolve()
    if not ref.exists():
        sys.exit(f"❌ Reference not found: {ref}")

    out_lut = Path(args.out).expanduser().resolve() if args.out else ref.parent / f"{ref.stem}_grade.cube"

    print(f"🖼  Reference: {ref}")
    print(f"⏳ Extracting {args.palette}-color palette...")
    palette, weights = extract_palette(ref, args.palette)
    print(f"   Palette (most → least frequent):")
    for c, w in zip(palette, weights):
        hex_c = "#{:02x}{:02x}{:02x}".format(int(c[0]*255), int(c[1]*255), int(c[2]*255))
        print(f"   {hex_c}  ({w*100:>5.1f}%)")

    print(f"\n⏳ Generating {LUT_SIZE}³ CUBE LUT (strength={args.strength})...")
    generate_cube_lut(palette, weights, args.strength, out_lut)
    print(f"✅ LUT: {out_lut}")
    print(f"   Use in render template: LUT_SRC = \"{out_lut}\"")

    if args.preview:
        prev = Path(args.preview).expanduser().resolve()
        out_video = prev.parent / f"{prev.stem}_graded_preview.mp4"
        print(f"\n⏳ Applying LUT to first 10s of {prev.name}...")
        apply_lut_preview(prev, out_lut, out_video)
        print(f"✅ Preview: {out_video}")


if __name__ == "__main__":
    main()
